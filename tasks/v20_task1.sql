-- =====================================================================
-- Вариант 20, задание 1
-- Величина:  сумма объёма поставок в денежном выражении (количество × цена1)
-- Период:    [21.08.2020, 20.08.2023]
-- Признак 1: категория товара
-- Признак 2: квартал (1-й, ..., 4-й)
-- Запуск:    s.bat tasks\v20_task1.sql [дата1 дата2 [категория]]
--            ./h v20 1 [дата1 дата2 [категория]]
-- =====================================================================
\set ON_ERROR_STOP on
\set QUIET on

\set date1 21.08.2020
\set date2 20.08.2023
\ir ../helper/params_dates.sql

\echo
\echo '=== Вариант 20 / Задание 1 ==='
\echo 'Сумма объёма поставок (ден. ед.) по категории товара и кварталу'
\echo 'Период:' :date1 '-' :date2
\if :is_arg3
    \echo 'Категория товара:' :arg3
\else
    \echo 'Категория товара: все категории'
\endif

\set QUIET off
WITH поставки AS (
    SELECT
        КАТЕГОРИЯ.наименование                      AS категория,
        EXTRACT(QUARTER FROM ПОСТАВКА.дата)::int     AS квартал,
        ПОСТАВКА.количество * ТОВАР.цена1           AS сумма
    FROM ПОСТАВКА
        INNER JOIN ТОВАР     ON ТОВАР.код = ПОСТАВКА.товар
        INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
    WHERE ПОСТАВКА.дата BETWEEN :'date1'::date AND :'date2'::date
)
SELECT
    категория                          AS "категория товара",
    квартал || '-й'                    AS "квартал",
    ROUND(SUM(сумма), 3)               AS "объём поставок, ден. ед."
FROM поставки
WHERE NOT :'is_arg3'::boolean OR категория = :'arg3'
GROUP BY категория, квартал
ORDER BY категория, квартал;
