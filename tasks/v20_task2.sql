-- Вариант 20, задание 2
-- Величина:  количество проданных товаров (шт)
-- Период:    [2019, 2023] (годы)
-- Признак 1: день недели (пн, вт, ..., вс)
-- Признак 2: район расположения поставщика
-- Запуск:    s.bat tasks\v20_task2.sql [год1 год2 [день недели]]
--            ./h v20 2 [год1 год2 [день недели]]
-- =====================================================================
\set ON_ERROR_STOP on
\set QUIET on

\set year1 2019
\set year2 2023
\ir ../helper/params_years.sql

\echo
\echo '=== Вариант 20 / Задание 2 ==='
\echo 'Количество проданных товаров (шт) по дню недели и району поставщика'
\echo 'Период:' :year1 '-' :year2
\if :is_arg3
    \echo 'День недели:' :arg3
\else
    \echo 'День недели: все дни'
\endif

\set QUIET off
WITH продажи AS (
    SELECT
        EXTRACT(ISODOW FROM ПРОДАЖА.дата)::int       AS день,
        (ARRAY['пн','вт','ср','чт','пт','сб','вс'])
            [EXTRACT(ISODOW FROM ПРОДАЖА.дата)::int] AS день_недели,
        РАЙОН.название                               AS район,
        ПРОДАЖА.количество                           AS количество
    FROM ПРОДАЖА
        INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
        INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
        INNER JOIN РАЙОН     ON РАЙОН.код = ПОСТАВЩИК.район
    WHERE EXTRACT(YEAR FROM ПРОДАЖА.дата) BETWEEN :year1 AND :year2
)
SELECT
    день_недели                        AS "день недели",
    район                              AS "район поставщика",
    SUM(количество)                    AS "продано, шт"
FROM продажи
WHERE NOT :'is_arg3'::boolean OR день_недели = :'arg3'
GROUP BY день, день_недели, район
ORDER BY день, район;
