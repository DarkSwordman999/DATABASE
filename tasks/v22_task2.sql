-- =====================================================================
-- Вариант 22, задание 2
-- Величина:  сумма затрат клиентов (количество × цена2 - стоимость покупок)
-- Период:    [2018, 2022] (годы)
-- Признак 1: время года (зима, весна, лето, осень)
-- Признак 2: пол клиента
-- Запуск:    s.bat tasks\v22_task2.sql [год1 год2 [время года]]
--            ./h v22 2 [год1 год2 [время года]]
-- =====================================================================
\set ON_ERROR_STOP on
\set QUIET on

\set year1 2018
\set year2 2022
\ir ../helper/params_years.sql

\echo
\echo '=== Вариант 22 / Задание 2 ==='
\echo 'Сумма затрат клиентов (ден. ед.) по времени года и полу клиента'
\echo 'Период:' :year1 '-' :year2
\if :is_arg3
    \echo 'Время года:' :arg3
\else
    \echo 'Время года: все сезоны'
\endif

\set QUIET off
WITH покупки AS (
    SELECT
        -- 1 - зима (дек, янв, фев), 2 - весна, 3 - лето, 4 - осень
        (EXTRACT(MONTH FROM ПРОДАЖА.дата)::int % 12) / 3 + 1 AS сезон,
        CASE КЛИЕНТ.пол WHEN B'0' THEN 'мужской' ELSE 'женский' END AS пол,
        ПРОДАЖА.количество * ТОВАР.цена2                     AS затраты
    FROM ПРОДАЖА
        INNER JOIN ТОВАР  ON ТОВАР.код = ПРОДАЖА.товар
        INNER JOIN КЛИЕНТ ON КЛИЕНТ.код = ПРОДАЖА.клиент
    WHERE EXTRACT(YEAR FROM ПРОДАЖА.дата) BETWEEN :year1 AND :year2
)
SELECT
    (ARRAY['зима','весна','лето','осень'])[сезон] AS "время года",
    пол                                           AS "пол клиента",
    ROUND(SUM(затраты), 3)                        AS "затраты клиентов, ден. ед."
FROM покупки
WHERE NOT :'is_arg3'::boolean
   OR (ARRAY['зима','весна','лето','осень'])[сезон] = :'arg3'
GROUP BY сезон, пол
ORDER BY сезон, пол DESC;
