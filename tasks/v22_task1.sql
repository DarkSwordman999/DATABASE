-- Вариант 22, задание 1
-- Величина:  сумма выручки торговой организации (количество × цена2)
-- Период:    [01.07.2019, 30.06.2023]
-- Признак 1: поставщик
-- Признак 2: декада месяца (1: 1-10, 2: 11-20, 3: 21-29/30/31)
-- Запуск:    s.bat tasks\v22_task1.sql [дата1 дата2 [поставщик]]
--            ./help v22 1 [дата1 дата2 [поставщик]]
-- =====================================================================
\set ON_ERROR_STOP on
\set QUIET on

\set date1 01.07.2019
\set date2 30.06.2023
\ir ../helper/params_dates.sql

\echo
\echo '=== Вариант 22 / Задание 1 ==='
\echo 'Сумма выручки (ден. ед.) по поставщику и декаде месяца'
\echo 'Период:' :date1 '-' :date2
\if :is_arg3
    \echo 'Поставщик:' :arg3
\else
    \echo 'Поставщик: все поставщики'
\endif

\set QUIET off
WITH продажи AS (
    SELECT
        ПОСТАВЩИК.название                           AS поставщик,
        CASE
            WHEN EXTRACT(DAY FROM ПРОДАЖА.дата) <= 10 THEN 1
            WHEN EXTRACT(DAY FROM ПРОДАЖА.дата) <= 20 THEN 2
            ELSE 3
        END                                          AS декада,
        ПРОДАЖА.количество * ТОВАР.цена2             AS выручка
    FROM ПРОДАЖА
        INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
        INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
    WHERE ПРОДАЖА.дата::date BETWEEN :'date1'::date AND :'date2'::date
)
SELECT
    поставщик                          AS "поставщик",
    (ARRAY['1-я (1-10)', '2-я (11-20)', '3-я (21-31)'])[декада]
                                       AS "декада месяца",
    ROUND(SUM(выручка), 3)             AS "выручка, ден. ед."
FROM продажи
WHERE NOT :'is_arg3'::boolean OR поставщик = :'arg3'
GROUP BY поставщик, декада
ORDER BY поставщик, декада;
