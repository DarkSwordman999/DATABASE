-- Запрос (*) варианта 22 - задание 1 ЛР1: выручка по поставщику и декаде месяца
-- за период 01.07.2019-30.06.2023
SELECT
    ПОСТАВЩИК.название                                  AS "поставщик",
    (ARRAY['1-я (1-10)', '2-я (11-20)', '3-я (21-31)'])
        [LEAST((EXTRACT(DAY FROM ПРОДАЖА.дата)::int - 1) / 10 + 1, 3)]
                                                        AS "декада месяца",
    ROUND(SUM(ПРОДАЖА.количество * ТОВАР.цена2), 3)     AS "выручка, ден. ед."
FROM ПРОДАЖА
    INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
    INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
WHERE ПРОДАЖА.дата::date BETWEEN DATE '2019-07-01' AND DATE '2023-06-30'
GROUP BY ПОСТАВЩИК.название, 2
ORDER BY ПОСТАВЩИК.название, 2;
