-- Запрос (*) варианта 20 - аналог задания 1 ЛР1.
-- В ЛР1 величина считалась по ПОСТАВКА (352 строки), объёмной в ЛР2 сделана ПРОДАЖА,
-- поэтому та же группировка (категория товара × квартал, период 21.08.2020-20.08.2023)
-- применяется к проданным товарам в ценах приобретения (количество × цена1).
SELECT
    КАТЕГОРИЯ.наименование                              AS "категория товара",
    EXTRACT(QUARTER FROM ПРОДАЖА.дата)::int || '-й'     AS "квартал",
    ROUND(SUM(ПРОДАЖА.количество * ТОВАР.цена1), 3)     AS "сумма, ден. ед."
FROM ПРОДАЖА
    INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
    INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
WHERE ПРОДАЖА.дата::date BETWEEN DATE '2020-08-21' AND DATE '2023-08-20'
GROUP BY КАТЕГОРИЯ.наименование, EXTRACT(QUARTER FROM ПРОДАЖА.дата)
ORDER BY КАТЕГОРИЯ.наименование, EXTRACT(QUARTER FROM ПРОДАЖА.дата);
