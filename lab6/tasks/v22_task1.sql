-- Величина:  сумма выручки торговой организации (количество × цена2)
-- Период:    [01.07.2019, 30.06.2023]
-- Признак 1: поставщик;  Признак 2: декада месяца (1: 1-10, 2: 11-20, 3: 21-29/30/31)
-- Запуск:    lab6\s.bat lab6\tasks\v22_task1.sql [дата1 дата2 [поставщик]]
--            ./help lr6 v22 1 [дата1 дата2 [поставщик]]
-- Параметры s.bat приходят с префиксом «#» (sqlcmd не принимает пустые -v);
-- пустой параметр - значение по умолчанию.
-- =====================================================================
SET NOCOUNT ON;
DECLARE @d1   date         = CONVERT(date, COALESCE(NULLIF(SUBSTRING(N'$(arg1)', 2, 100), N''), N'01.07.2019'), 104);
DECLARE @d2   date         = CONVERT(date, COALESCE(NULLIF(SUBSTRING(N'$(arg2)', 2, 100), N''), N'30.06.2023'), 104);
DECLARE @prov nvarchar(40) = NULLIF(SUBSTRING(N'$(arg3)', 2, 100), N'');

PRINT N'=== Вариант 22 / Задание 1 (MS SQL Server) ===';
PRINT N'Сумма выручки (ден. ед.) по поставщику и декаде месяца';
PRINT N'Период: ' + CONVERT(nvarchar(10), @d1, 104) + N' - ' + CONVERT(nvarchar(10), @d2, 104);
PRINT N'Поставщик: ' + COALESCE(@prov, N'все поставщики');

WITH продажи AS (
    SELECT
        ПОСТАВЩИК.название                       AS поставщик,
        CASE WHEN DAY(ПРОДАЖА.дата) <= 10 THEN 1
             WHEN DAY(ПРОДАЖА.дата) <= 20 THEN 2
             ELSE 3 END                          AS декада,
        ПРОДАЖА.количество * ТОВАР.цена2         AS выручка
    FROM ПРОДАЖА
        INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
        INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
    WHERE CAST(ПРОДАЖА.дата AS date) BETWEEN @d1 AND @d2
)
SELECT поставщик                                                        AS [поставщик],
       CHOOSE(декада, N'1-я (1-10)', N'2-я (11-20)', N'3-я (21-31)')   AS [декада месяца],
       CAST(SUM(выручка) AS decimal(18,3))                             AS [выручка, ден. ед.]
FROM продажи
WHERE @prov IS NULL OR поставщик = @prov
GROUP BY поставщик, декада
ORDER BY поставщик, декада;
