-- Величина:  сумма объёма поставок в денежном выражении (количество × цена1)
-- Период:    [21.08.2020, 20.08.2023]
-- Признак 1: категория товара;  Признак 2: квартал (1-й, ..., 4-й)
-- Запуск:    lab6\s.bat lab6\tasks\v20_task1.sql [дата1 дата2 [категория]]
--            ./help lr6 v20 1 [дата1 дата2 [категория]]
-- Параметры s.bat приходят с префиксом «#» (sqlcmd не принимает пустые -v);
-- пустой параметр - значение по умолчанию.
-- =====================================================================
SET NOCOUNT ON;
DECLARE @d1  date         = CONVERT(date, COALESCE(NULLIF(SUBSTRING(N'$(arg1)', 2, 100), N''), N'21.08.2020'), 104);
DECLARE @d2  date         = CONVERT(date, COALESCE(NULLIF(SUBSTRING(N'$(arg2)', 2, 100), N''), N'20.08.2023'), 104);
DECLARE @cat nvarchar(20) = NULLIF(SUBSTRING(N'$(arg3)', 2, 100), N'');

PRINT N'=== Вариант 20 / Задание 1 (MS SQL Server) ===';
PRINT N'Сумма объёма поставок (ден. ед.) по категории товара и кварталу';
PRINT N'Период: ' + CONVERT(nvarchar(10), @d1, 104) + N' - ' + CONVERT(nvarchar(10), @d2, 104);
PRINT N'Категория товара: ' + COALESCE(@cat, N'все категории');

SELECT
    КАТЕГОРИЯ.наименование                                        AS [категория товара],
    CAST(DATEPART(QUARTER, ПОСТАВКА.дата) AS nvarchar(1)) + N'-й'  AS [квартал],
    CAST(SUM(ПОСТАВКА.количество * ТОВАР.цена1) AS decimal(18,3)) AS [объём поставок, ден. ед.]
FROM ПОСТАВКА
    INNER JOIN ТОВАР     ON ТОВАР.код = ПОСТАВКА.товар
    INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
WHERE ПОСТАВКА.дата BETWEEN @d1 AND @d2
  AND (@cat IS NULL OR КАТЕГОРИЯ.наименование = @cat)
GROUP BY КАТЕГОРИЯ.наименование, DATEPART(QUARTER, ПОСТАВКА.дата)
ORDER BY КАТЕГОРИЯ.наименование, DATEPART(QUARTER, ПОСТАВКА.дата);
