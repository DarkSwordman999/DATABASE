-- Величина:  сумма затрат клиентов (количество × цена2 - стоимость покупок)
-- Период:    [2018, 2022] (годы)
-- Признак 1: время года (зима, весна, лето, осень);  Признак 2: пол клиента
-- Запуск:    lab6\s.bat lab6\tasks\v22_task2.sql [год1 год2 [время года]]
--            ./h lr6 v22 2 [год1 год2 [время года]]
-- Параметры s.bat приходят с префиксом «#» (sqlcmd не принимает пустые -v);
-- пустой параметр - значение по умолчанию.
-- =====================================================================
SET NOCOUNT ON;
DECLARE @y1     int          = CAST(COALESCE(NULLIF(SUBSTRING(N'$(arg1)', 2, 100), N''), N'2018') AS int);
DECLARE @y2     int          = CAST(COALESCE(NULLIF(SUBSTRING(N'$(arg2)', 2, 100), N''), N'2022') AS int);
DECLARE @season nvarchar(10) = NULLIF(SUBSTRING(N'$(arg3)', 2, 100), N'');

PRINT N'=== Вариант 22 / Задание 2 (MS SQL Server) ===';
PRINT N'Сумма затрат клиентов (ден. ед.) по времени года и полу клиента';
PRINT N'Период: ' + CAST(@y1 AS nvarchar(4)) + N' - ' + CAST(@y2 AS nvarchar(4));
PRINT N'Время года: ' + COALESCE(@season, N'все сезоны');

WITH покупки AS (
    SELECT
        -- 1 - зима (дек, янв, фев), 2 - весна, 3 - лето, 4 - осень
        (MONTH(ПРОДАЖА.дата) % 12) / 3 + 1                            AS сезон,
        CASE КЛИЕНТ.пол WHEN 0 THEN N'мужской' ELSE N'женский' END    AS пол,
        ПРОДАЖА.количество * ТОВАР.цена2                              AS затраты
    FROM ПРОДАЖА
        INNER JOIN ТОВАР  ON ТОВАР.код = ПРОДАЖА.товар
        INNER JOIN КЛИЕНТ ON КЛИЕНТ.код = ПРОДАЖА.клиент
    WHERE YEAR(ПРОДАЖА.дата) BETWEEN @y1 AND @y2
)
SELECT CHOOSE(сезон, N'зима', N'весна', N'лето', N'осень')   AS [время года],
       пол                                                    AS [пол клиента],
       CAST(SUM(затраты) AS decimal(18,3))                    AS [затраты клиентов, ден. ед.]
FROM покупки
WHERE @season IS NULL OR CHOOSE(сезон, N'зима', N'весна', N'лето', N'осень') = @season
GROUP BY сезон, пол
ORDER BY сезон, пол DESC;
