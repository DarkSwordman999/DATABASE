-- Величина:  количество проданных товаров (шт)
-- Период:    [2019, 2023] (годы)
-- Признак 1: день недели (пн, вт, ..., вс);  Признак 2: район расположения поставщика
-- Запуск:    lab6\s.bat lab6\tasks\v20_task2.sql [год1 год2 [день недели]]
--            ./help lr6 v20 2 [год1 год2 [день недели]]
-- Параметры s.bat приходят с префиксом «#» (sqlcmd не принимает пустые -v);
-- пустой параметр - значение по умолчанию.
-- =====================================================================
SET NOCOUNT ON;
SET DATEFIRST 1;     -- понедельник - 1-й день недели
DECLARE @y1  int         = CAST(COALESCE(NULLIF(SUBSTRING(N'$(arg1)', 2, 100), N''), N'2019') AS int);
DECLARE @y2  int         = CAST(COALESCE(NULLIF(SUBSTRING(N'$(arg2)', 2, 100), N''), N'2023') AS int);
DECLARE @day nvarchar(2) = NULLIF(SUBSTRING(N'$(arg3)', 2, 100), N'');

PRINT N'=== Вариант 20 / Задание 2 (MS SQL Server) ===';
PRINT N'Количество проданных товаров (шт) по дню недели и району поставщика';
PRINT N'Период: ' + CAST(@y1 AS nvarchar(4)) + N' - ' + CAST(@y2 AS nvarchar(4));
PRINT N'День недели: ' + COALESCE(@day, N'все дни');

WITH продажи AS (
    SELECT
        DATEPART(WEEKDAY, ПРОДАЖА.дата)                             AS день,
        CHOOSE(DATEPART(WEEKDAY, ПРОДАЖА.дата),
               N'пн', N'вт', N'ср', N'чт', N'пт', N'сб', N'вс')    AS день_недели,
        РАЙОН.название                                               AS район,
        ПРОДАЖА.количество                                           AS количество
    FROM ПРОДАЖА
        INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
        INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
        INNER JOIN РАЙОН     ON РАЙОН.код = ПОСТАВЩИК.район
    WHERE YEAR(ПРОДАЖА.дата) BETWEEN @y1 AND @y2
)
SELECT день_недели       AS [день недели],
       район             AS [район поставщика],
       SUM(количество)   AS [продано, шт]
FROM продажи
WHERE @day IS NULL OR день_недели = @day
GROUP BY день, день_недели, район
ORDER BY день, район;
