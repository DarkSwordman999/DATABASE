-- Среднее количество товара в одной продаже по категориям (аналог TAXI: средний пробег по классам)
-- Запуск: ./help 27
SELECT КАТЕГОРИЯ.наименование AS категория, round(avg(ПРОДАЖА.количество), 2) AS среднее_количество
FROM ПРОДАЖА
INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
GROUP BY КАТЕГОРИЯ.наименование
ORDER BY КАТЕГОРИЯ.наименование;
