-- 10 последних продаж (аналог TAXI: примеры поездок)
-- Запуск: ./help 05
SELECT ПРОДАЖА.дата,
       МАГАЗИН.название                     AS магазин,
       ТОВАР.наименование                   AS товар,
       КЛИЕНТ.фамилия || ' ' || КЛИЕНТ.имя  AS клиент,
       ПРОДАЖА.количество,
       round(ПРОДАЖА.количество * ТОВАР.цена2, 2) AS сумма
FROM ПРОДАЖА
INNER JOIN ТОВАР   ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN МАГАЗИН ON МАГАЗИН.код = ПРОДАЖА.магазин
LEFT JOIN  КЛИЕНТ  ON КЛИЕНТ.код = ПРОДАЖА.клиент
ORDER BY ПРОДАЖА.дата DESC
LIMIT 10;
