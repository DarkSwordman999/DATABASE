-- Топ-5 клиентов по сумме покупок (аналог TAXI)
-- Запуск: ./help 26
SELECT КЛИЕНТ.фамилия, КЛИЕНТ.имя, count(*) AS покупок, round(sum(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS сумма
FROM КЛИЕНТ
INNER JOIN ПРОДАЖА ON ПРОДАЖА.клиент = КЛИЕНТ.код
INNER JOIN ТОВАР   ON ТОВАР.код = ПРОДАЖА.товар
GROUP BY КЛИЕНТ.код, КЛИЕНТ.фамилия, КЛИЕНТ.имя
ORDER BY сумма DESC
LIMIT 5;
