-- Статистика продаж по категориям товаров (аналог TAXI: статистика по классам)
-- Запуск: ./help 22
SELECT КАТЕГОРИЯ.наименование AS категория, count(*) AS продаж,
       round(avg(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS средний_чек, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка
FROM ПРОДАЖА
INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
GROUP BY КАТЕГОРИЯ.наименование
ORDER BY КАТЕГОРИЯ.наименование;
