-- ДЕМОНСТРАЦИЯ INNER JOIN: продажи с товаром, магазином и клиентом
-- Запуск: ./help 07
SELECT ПРОДАЖА.дата, ТОВАР.наименование AS товар, МАГАЗИН.название AS магазин,
       КЛИЕНТ.фамилия AS клиент, ПРОДАЖА.количество,
       round(ПРОДАЖА.количество * ТОВАР.цена2, 2) AS сумма
FROM ПРОДАЖА
INNER JOIN ТОВАР   ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN МАГАЗИН ON МАГАЗИН.код = ПРОДАЖА.магазин
INNER JOIN КЛИЕНТ  ON КЛИЕНТ.код = ПРОДАЖА.клиент
ORDER BY ПРОДАЖА.дата
LIMIT 10;
