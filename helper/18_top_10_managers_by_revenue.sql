-- Топ-10 сотрудников по выручке магазинов в периоды их работы (аналог TAXI: топ-10 водителей)
-- Продажа засчитывается сотруднику, если он работал в этом магазине в день продажи (РАБОТА)
-- Запуск: ./help 18
SELECT СОТРУДНИК.имя AS сотрудник, count(*) AS продаж, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка
FROM ПРОДАЖА
INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN РАБОТА    ON РАБОТА.магазин = ПРОДАЖА.магазин
                    AND ПРОДАЖА.дата::date BETWEEN РАБОТА.дата1::date AND РАБОТА.дата2::date
INNER JOIN СОТРУДНИК ON СОТРУДНИК.код = РАБОТА.сотрудник
GROUP BY СОТРУДНИК.имя
ORDER BY выручка DESC
LIMIT 10;
