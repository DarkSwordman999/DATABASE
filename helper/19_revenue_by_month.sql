-- Выручка по месяцам (аналог TAXI)
-- Запуск: ./help 19
SELECT EXTRACT(MONTH FROM ПРОДАЖА.дата)::int AS "№",
       (ARRAY['январь','февраль','март','апрель','май','июнь','июль','август','сентябрь',
              'октябрь','ноябрь','декабрь'])[EXTRACT(MONTH FROM ПРОДАЖА.дата)::int] AS месяц,
       round(sum(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS выручка
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
GROUP BY 1, 2
ORDER BY 1;
