-- ДЕМОНСТРАЦИЯ LEFT JOIN: все товары и число их продаж (товар без продаж тоже выводится)
-- Запуск: ./help 08
SELECT ТОВАР.код, ТОВАР.наименование, count(ПРОДАЖА.товар) AS количество_продаж
FROM ТОВАР
LEFT JOIN ПРОДАЖА ON ПРОДАЖА.товар = ТОВАР.код
GROUP BY ТОВАР.код, ТОВАР.наименование
ORDER BY количество_продаж DESC
LIMIT 10;
