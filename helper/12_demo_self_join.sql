-- ДЕМОНСТРАЦИЯ SELF JOIN: пары товаров одной категории, где первый дороже второго
-- Запуск: ./help 12
SELECT Т1.наименование AS "товар 1", round(Т1.цена2, 2) AS "цена продажи 1",
       Т2.наименование AS "товар 2", round(Т2.цена2, 2) AS "цена продажи 2"
FROM ТОВАР Т1, ТОВАР Т2
WHERE Т1.категория = Т2.категория AND Т1.цена2 > Т2.цена2 AND Т1.код != Т2.код
ORDER BY Т1.цена2 DESC, Т2.цена2 DESC
LIMIT 10;
