-- Загруженность сотрудников: число смен и рабочих дней (аналог TAXI: загруженность водителей)
-- Запуск: ./help 23
SELECT СОТРУДНИК.имя AS сотрудник, count(*) AS смен,
       sum(РАБОТА.дата2::date - РАБОТА.дата1::date + 1) AS "рабочих дней",
       sum(CASE WHEN РАБОТА.старший = '1' THEN 1 ELSE 0 END) AS "смен старшим"
FROM СОТРУДНИК
INNER JOIN РАБОТА ON РАБОТА.сотрудник = СОТРУДНИК.код
GROUP BY СОТРУДНИК.имя
ORDER BY "рабочих дней" DESC;
