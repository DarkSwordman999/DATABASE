-- Топ-10 товаров по выручке (аналог TAXI: топ-10 авто по выручке)
-- Запуск: ./help 17
SELECT ТОВАР.наименование AS товар, sum(ПРОДАЖА.количество) AS "продано, шт",
       round(sum(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS выручка
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
GROUP BY ТОВАР.наименование
ORDER BY выручка DESC
LIMIT 10;
