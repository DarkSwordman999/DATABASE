-- Все сотрудники: число смен, период работы и последний магазин (аналог TAXI: все водители)
-- Запуск: ./help 02
\echo '=== СОТРУДНИКИ ==='
SELECT СОТРУДНИК.код, СОТРУДНИК.имя,
       count(РАБОТА.сотрудник)      AS смен,
       min(РАБОТА.дата1)::date      AS начало,
       max(РАБОТА.дата2)::date      AS окончание,
       (SELECT МАГАЗИН.название
          FROM РАБОТА Р JOIN МАГАЗИН ON МАГАЗИН.код = Р.магазин
         WHERE Р.сотрудник = СОТРУДНИК.код
         ORDER BY Р.дата2 DESC LIMIT 1) AS последний_магазин
FROM СОТРУДНИК
LEFT JOIN РАБОТА ON РАБОТА.сотрудник = СОТРУДНИК.код
GROUP BY СОТРУДНИК.код, СОТРУДНИК.имя
ORDER BY СОТРУДНИК.код;
