-- Все товары с категорией и поставщиком (аналог TAXI: все автомобили)
-- Запуск: ./help 01
\echo '=== ТОВАРЫ ==='
SELECT ТОВАР.код, ТОВАР.наименование, ТОВАР.цена1, ТОВАР.цена2,
       КАТЕГОРИЯ.наименование AS категория, ПОСТАВЩИК.название AS поставщик, ТОВАР.хранение
FROM ТОВАР
LEFT JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
LEFT JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
ORDER BY ТОВАР.код;
