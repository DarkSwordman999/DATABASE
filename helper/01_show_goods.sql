-- Все товары с категорией и поставщиком (аналог TAXI: все автомобили)
-- Запуск: ./help 01
\echo '=== ТОВАРЫ ==='
SELECT ТОВАР.код, ТОВАР.наименование AS товар,
       round(ТОВАР.цена1, 2) AS "цена закупки", round(ТОВАР.цена2, 2) AS "цена продажи",
       КАТЕГОРИЯ.наименование AS категория, ПОСТАВЩИК.название AS поставщик,
       round(ТОВАР.хранение, 2) AS "хранение в день"
FROM ТОВАР
LEFT JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
LEFT JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
ORDER BY ТОВАР.код;
