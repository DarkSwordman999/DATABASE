-- ДЕМОНСТРАЦИЯ CROSS JOIN: все сочетания магазинов и категорий товаров
-- Запуск: ./help 11
SELECT МАГАЗИН.код AS код_магазина, МАГАЗИН.название AS магазин,
       КАТЕГОРИЯ.код AS код_категории, КАТЕГОРИЯ.наименование AS категория
FROM МАГАЗИН
CROSS JOIN КАТЕГОРИЯ
ORDER BY МАГАЗИН.код, КАТЕГОРИЯ.код
LIMIT 10;
