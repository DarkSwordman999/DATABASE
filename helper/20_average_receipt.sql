-- Средний, минимальный и максимальный чек одной продажи (аналог TAXI: средний чек)
-- Запуск: ./help 20
SELECT round(avg(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS средний_чек,
       min(ПРОДАЖА.количество * ТОВАР.цена2)           AS минимальный_чек,
       max(ПРОДАЖА.количество * ТОВАР.цена2)           AS максимальный_чек
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар;
