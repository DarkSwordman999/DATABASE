-- Средний, минимальный и максимальный чек одной продажи (аналог TAXI: средний чек)
-- Запуск: ./help 20
SELECT round(avg(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS "средний чек",
       round(min(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS "минимальный чек",
       round(max(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS "максимальный чек"
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар;
