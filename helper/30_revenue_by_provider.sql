-- Выручка по поставщикам с районом поставщика (аналог TAXI: выручка по водителям с рейтингом)
-- Запуск: ./help 30
SELECT ПОСТАВЩИК.название AS поставщик, РАЙОН.название AS район, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка
FROM ПРОДАЖА
INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
LEFT JOIN  РАЙОН     ON РАЙОН.код = ПОСТАВЩИК.район
GROUP BY ПОСТАВЩИК.название, РАЙОН.название
ORDER BY выручка DESC;
