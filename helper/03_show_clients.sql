\echo '=== КЛИЕНТЫ (первые 10) ==='
SELECT КЛИЕНТ.код, КЛИЕНТ.фамилия, КЛИЕНТ.имя, КЛИЕНТ.отчество,
       CASE КЛИЕНТ.пол WHEN '1' THEN 'ж' ELSE 'м' END AS пол,
       КЛИЕНТ.дата_рожд AS "дата рождения", РАЙОН.название AS район
FROM КЛИЕНТ
LEFT JOIN РАЙОН ON РАЙОН.код = КЛИЕНТ.район
ORDER BY КЛИЕНТ.код
LIMIT 10;
