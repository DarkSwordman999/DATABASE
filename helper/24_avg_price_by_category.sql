-- Средние цены по категориям товаров (аналог TAXI: средняя стоимость по классам)
-- Запуск: ./help 24
SELECT КАТЕГОРИЯ.наименование AS категория, count(*) AS товаров,
       round(avg(ТОВАР.цена1), 2) AS "средняя цена закупки", round(avg(ТОВАР.цена2), 2) AS "средняя цена продажи",
       round(avg(ТОВАР.цена2 - ТОВАР.цена1), 2) AS "средняя наценка"
FROM ТОВАР
INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
GROUP BY КАТЕГОРИЯ.наименование
ORDER BY КАТЕГОРИЯ.наименование;
