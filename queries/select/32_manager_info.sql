-- Информация о сотруднике и его сменах (аналог TAXI 32: информация о водителе)
-- arg1 - код сотрудника
-- Запуск: ./help 32 1
SELECT * FROM СОТРУДНИК WHERE код = :'arg1'::int;
SELECT РАБОТА.дата1::date AS начало, РАБОТА.дата2::date AS окончание, МАГАЗИН.название AS магазин,
       CASE WHEN РАБОТА.старший = '1' THEN 'старший' ELSE 'рядовой' END AS должность
FROM РАБОТА
INNER JOIN МАГАЗИН ON МАГАЗИН.код = РАБОТА.магазин
WHERE РАБОТА.сотрудник = :'arg1'::int
ORDER BY РАБОТА.дата1;
