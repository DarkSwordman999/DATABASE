-- Магазины с выручкой выше заданной суммы (HAVING, аналог TAXI 35)
-- arg1 - сумма
-- Запуск: ./help 35 100000
SELECT МАГАЗИН.название AS магазин, round(sum(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS выручка
FROM МАГАЗИН
INNER JOIN ПРОДАЖА ON ПРОДАЖА.магазин = МАГАЗИН.код
INNER JOIN ТОВАР   ON ТОВАР.код = ПРОДАЖА.товар
GROUP BY МАГАЗИН.название
HAVING sum(ПРОДАЖА.количество * ТОВАР.цена2) > :'arg1'::numeric
ORDER BY выручка DESC;
