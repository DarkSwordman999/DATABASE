-- Продажи дороже заданной суммы, 10 самых дорогих (аналог TAXI 34)
-- arg1 - сумма
-- Запуск: ./help 34 3000
SELECT ПРОДАЖА.дата, ТОВАР.наименование AS товар, ПРОДАЖА.количество, ПРОДАЖА.количество * ТОВАР.цена2 AS сумма
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
WHERE ПРОДАЖА.количество * ТОВАР.цена2 > :'arg1'::numeric
ORDER BY сумма DESC
LIMIT 10;
