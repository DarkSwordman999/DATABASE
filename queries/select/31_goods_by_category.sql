-- Товары заданной категории (аналог TAXI 31: авто по классу)
-- arg1 - категория (часть наименования): мебель, одежда
-- Запуск: ./help 31 мебель
\echo '=== ТОВАРЫ КАТЕГОРИИ: ' :arg1 ' ==='
SELECT ТОВАР.код, ТОВАР.наименование, ТОВАР.цена1, ТОВАР.цена2, ПОСТАВЩИК.название AS поставщик
FROM ТОВАР
INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
LEFT JOIN  ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
WHERE КАТЕГОРИЯ.наименование ILIKE '%' || :'arg1' || '%'
ORDER BY ТОВАР.код;
