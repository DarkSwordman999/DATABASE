-- История продаж товара: последние 10 (аналог TAXI 33: история поездок авто)
-- arg1 - код товара
-- Запуск: ./help 33 1
SELECT ПРОДАЖА.дата, МАГАЗИН.название AS магазин, ПРОДАЖА.количество, round(ПРОДАЖА.количество * ТОВАР.цена2, 2) AS сумма
FROM ПРОДАЖА
INNER JOIN ТОВАР   ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN МАГАЗИН ON МАГАЗИН.код = ПРОДАЖА.магазин
WHERE ПРОДАЖА.товар = :'arg1'::int
ORDER BY ПРОДАЖА.дата DESC
LIMIT 10;
