-- Технологическое представление V_ПРОДАЖИ_ТЕХ: коды и вычисляемые признаки
-- (год, квартал, месяц, декада, день недели, время года), выручка и затраты (аналог TAXI 101)
-- Запуск: ./help 101
CREATE OR REPLACE VIEW V_ПРОДАЖИ_ТЕХ AS
SELECT ПРОДАЖА.дата::date                                  AS дата,
       EXTRACT(YEAR FROM ПРОДАЖА.дата)::int                AS год,
       EXTRACT(QUARTER FROM ПРОДАЖА.дата)::int             AS квартал,
       EXTRACT(MONTH FROM ПРОДАЖА.дата)::int               AS месяц,
       LEAST((EXTRACT(DAY FROM ПРОДАЖА.дата)::int - 1) / 10 + 1, 3) AS декада,
       EXTRACT(ISODOW FROM ПРОДАЖА.дата)::int              AS день_недели,
       (ARRAY['зима','зима','весна','весна','весна','лето','лето','лето',
              'осень','осень','осень','зима'])[EXTRACT(MONTH FROM ПРОДАЖА.дата)::int] AS время_года,
       ПРОДАЖА.магазин, ПРОДАЖА.товар, ТОВАР.категория, ТОВАР.поставщик, ПРОДАЖА.клиент,
       ПРОДАЖА.количество,
       ПРОДАЖА.количество * ТОВАР.цена2                    AS выручка,
       ПРОДАЖА.количество * ТОВАР.цена1                    AS затраты
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар;
