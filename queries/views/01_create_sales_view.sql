-- Пользовательское представление V_ПРОДАЖИ: продажи с наименованиями (аналог TAXI 100)
-- Запуск: ./help 100
CREATE OR REPLACE VIEW V_ПРОДАЖИ AS
SELECT ПРОДАЖА.дата,
       МАГАЗИН.название                     AS магазин,
       ТОВАР.наименование                   AS товар,
       КАТЕГОРИЯ.наименование               AS категория,
       ПОСТАВЩИК.название                   AS поставщик,
       КЛИЕНТ.фамилия || ' ' || КЛИЕНТ.имя  AS клиент,
       ПРОДАЖА.количество,
       ТОВАР.цена2                          AS цена,
       ПРОДАЖА.количество * ТОВАР.цена2     AS сумма
FROM ПРОДАЖА
INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN МАГАЗИН   ON МАГАЗИН.код = ПРОДАЖА.магазин
LEFT JOIN  КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
LEFT JOIN  ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
LEFT JOIN  КЛИЕНТ    ON КЛИЕНТ.код = ПРОДАЖА.клиент;
\echo 'Представление V_ПРОДАЖИ создано (queries/views/01_create_sales_view.sql)'
