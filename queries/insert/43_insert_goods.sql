-- Добавить товар (аналог TAXI 43: добавить авто). Код - следующий свободный,
-- оптовая цена1 = 80 % от розничной, поставщик и хранение не заданы.
-- arg1 - наименование, arg2 - категория (наименование), arg3 - розничная цена2
-- Запуск: ./help 43 тумба мебель 120
INSERT INTO ТОВАР (код, наименование, цена1, цена2, категория)
SELECT coalesce(max(ТОВАР.код), 0) + 1, :'arg1', round(:'arg3'::numeric * 0.8, 2), :'arg3'::numeric,
       (SELECT код FROM КАТЕГОРИЯ WHERE наименование = :'arg2')
FROM ТОВАР;
SELECT * FROM ТОВАР ORDER BY код DESC LIMIT 1;
