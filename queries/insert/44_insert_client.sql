-- Добавить клиента (аналог TAXI 44: добавить водителя). Код - следующий свободный.
-- arg1 - фамилия, arg2 - имя, arg3 - код района (необязательно)
-- Запуск: ./help 44 Иванов Пётр 2
INSERT INTO КЛИЕНТ (код, фамилия, имя, район)
SELECT coalesce(max(код), 0) + 1, :'arg1', :'arg2', nullif(:'arg3', '')::int
FROM КЛИЕНТ;
SELECT * FROM КЛИЕНТ ORDER BY код DESC LIMIT 1;
