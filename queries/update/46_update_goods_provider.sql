-- Изменить поставщика товара (аналог TAXI 46: изменить рейтинг водителя)
-- arg1 - код товара, arg2 - код поставщика
-- Запуск: ./help 46 1 3
UPDATE ТОВАР SET поставщик = :'arg2'::int WHERE код = :'arg1'::int;
SELECT ТОВАР.*, ПОСТАВЩИК.название AS поставщик_
FROM ТОВАР LEFT JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
WHERE ТОВАР.код = :'arg1'::int;
