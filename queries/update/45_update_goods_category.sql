-- Изменить категорию товара (аналог TAXI 45: изменить класс авто)
-- arg1 - код товара, arg2 - категория (наименование)
-- Запуск: ./help 45 7 одежда
UPDATE ТОВАР SET категория = (SELECT код FROM КАТЕГОРИЯ WHERE наименование = :'arg2')
WHERE код = :'arg1'::int;
SELECT ТОВАР.*, КАТЕГОРИЯ.наименование AS категория_
FROM ТОВАР LEFT JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
WHERE ТОВАР.код = :'arg1'::int;
