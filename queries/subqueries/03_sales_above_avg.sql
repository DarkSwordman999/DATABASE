-- Задача 2.1: продажи дороже средней продажи своей категории
-- (коррелированный подзапрос в WHERE, аналог TAXI 112)
-- Запуск: ./help 112
SELECT ПРОДАЖА.дата, ТОВАР.наименование AS товар, ТОВАР.категория, ПРОДАЖА.количество * ТОВАР.цена2 AS сумма
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
WHERE ПРОДАЖА.количество * ТОВАР.цена2 > (SELECT avg(П.количество * Т.цена2)
                  FROM ПРОДАЖА П INNER JOIN ТОВАР Т ON Т.код = П.товар
                 WHERE Т.категория = ТОВАР.категория)
ORDER BY сумма DESC
LIMIT 10;
