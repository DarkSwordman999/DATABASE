-- Задача 2.1: продажи дороже средней продажи своей категории
-- (коррелированный подзапрос в WHERE, аналог TAXI 112)
-- Средние по категориям считаются один раз (CTE MATERIALIZED), коррелированный подзапрос
-- берёт среднее своей категории из этой маленькой таблицы - иначе на 2 млн продаж (ЛР2)
-- среднее пересчитывалось бы для каждой строки и запрос выполнялся бы часами.
-- Запуск: ./help 112
WITH средние AS MATERIALIZED (
    SELECT Т.категория, avg(П.количество * Т.цена2) AS средняя
      FROM ПРОДАЖА П INNER JOIN ТОВАР Т ON Т.код = П.товар
     GROUP BY Т.категория
)
SELECT ПРОДАЖА.дата, ТОВАР.наименование AS товар, КАТЕГОРИЯ.наименование AS категория,
       ПРОДАЖА.количество * ТОВАР.цена2 AS сумма,
       round((SELECT средняя FROM средние WHERE средние.категория = ТОВАР.категория), 2)
           AS "средняя по категории"
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
WHERE ПРОДАЖА.количество * ТОВАР.цена2 > (SELECT средняя FROM средние
                                           WHERE средние.категория = ТОВАР.категория)
ORDER BY сумма DESC
LIMIT 10;
