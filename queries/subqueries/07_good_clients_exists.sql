-- Задача 4.2: клиенты без мелких покупок (нет покупок дешевле 40) - NOT EXISTS (аналог TAXI 116)
-- Запуск: ./help 116
SELECT КЛИЕНТ.код, КЛИЕНТ.фамилия, КЛИЕНТ.имя
FROM КЛИЕНТ
WHERE EXISTS (SELECT 1 FROM ПРОДАЖА WHERE ПРОДАЖА.клиент = КЛИЕНТ.код)
  AND NOT EXISTS (SELECT 1
                    FROM ПРОДАЖА INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
                   WHERE ПРОДАЖА.клиент = КЛИЕНТ.код
                     AND ПРОДАЖА.количество * ТОВАР.цена2 < 40)
ORDER BY КЛИЕНТ.код;
