-- Задача 4.3: лучший магазин - выручка не меньше выручки ВСЕХ магазинов (>= ALL, аналог TAXI 117)
-- Запуск: ./help 117
SELECT МАГАЗИН.название AS магазин, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка
FROM ПРОДАЖА
INNER JOIN ТОВАР   ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN МАГАЗИН ON МАГАЗИН.код = ПРОДАЖА.магазин
GROUP BY МАГАЗИН.название
HAVING sum(ПРОДАЖА.количество * ТОВАР.цена2) >= ALL (SELECT sum(П.количество * Т.цена2)
                              FROM ПРОДАЖА П INNER JOIN ТОВАР Т ON Т.код = П.товар
                             GROUP BY П.магазин);
