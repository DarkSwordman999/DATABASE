-- Задача 4.1: покупки клиента дороже его средней покупки (параметр, аналог TAXI 115)
-- arg1 - фамилия клиента
-- Средние покупки клиентов с этой фамилией считаются один раз (CTE MATERIALIZED),
-- коррелированный подзапрос берёт среднее своего клиента из этой маленькой таблицы -
-- иначе на 2 млн продаж (ЛР2) среднее пересчитывалось бы для каждой покупки.
-- Запуск: ./help 115 Воронов
\echo '=== ПОКУПКИ КЛИЕНТА' :arg1 'ДОРОЖЕ ЕГО СРЕДНЕЙ ПОКУПКИ ==='
WITH средние AS MATERIALIZED (
    SELECT П.клиент, avg(П.количество * Т.цена2) AS средняя
      FROM ПРОДАЖА П
           INNER JOIN ТОВАР  Т ON Т.код = П.товар
           INNER JOIN КЛИЕНТ К ON К.код = П.клиент
     WHERE К.фамилия = :'arg1'
     GROUP BY П.клиент
)
SELECT КЛИЕНТ.фамилия, КЛИЕНТ.имя, ПРОДАЖА.дата, ТОВАР.наименование AS товар,
       ПРОДАЖА.количество * ТОВАР.цена2 AS сумма,
       round((SELECT средняя FROM средние WHERE средние.клиент = ПРОДАЖА.клиент), 2)
           AS "средняя покупка клиента"
FROM ПРОДАЖА
INNER JOIN ТОВАР  ON ТОВАР.код = ПРОДАЖА.товар
INNER JOIN КЛИЕНТ ON КЛИЕНТ.код = ПРОДАЖА.клиент
WHERE КЛИЕНТ.фамилия = :'arg1'
  AND ПРОДАЖА.количество * ТОВАР.цена2 > (SELECT средняя FROM средние
                                          WHERE средние.клиент = ПРОДАЖА.клиент)
ORDER BY сумма DESC
LIMIT 10;
