-- Задача 1.2: рейтинг товаров по выручке (подзапрос в FROM + оконная функция RANK,
-- аналог TAXI 111: рейтинг автомобилей)
-- Запуск: ./help 111
SELECT rank() OVER (ORDER BY в.выручка DESC) AS место, в.товар, round(в.выручка, 2) AS выручка,
       round(в.выручка * 100.0 / sum(в.выручка) OVER (), 2) AS "доля, %"
FROM (SELECT ТОВАР.наименование AS товар, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка
        FROM ПРОДАЖА INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
       GROUP BY ТОВАР.наименование) в
ORDER BY место;
