-- Задача 2.2: статистика по категориям (подзапрос в FROM, аналог TAXI 113)
-- Запуск: ./help 113
SELECT КАТЕГОРИЯ.наименование AS категория, с.продаж, с.выручка, с.средний_чек, с.макс_чек
FROM (SELECT ТОВАР.категория, count(*) AS продаж, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка,
             round(avg(ПРОДАЖА.количество * ТОВАР.цена2), 2) AS средний_чек, max(ПРОДАЖА.количество * ТОВАР.цена2) AS макс_чек
        FROM ПРОДАЖА INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
       GROUP BY ТОВАР.категория) с
INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = с.категория
ORDER BY КАТЕГОРИЯ.наименование;
