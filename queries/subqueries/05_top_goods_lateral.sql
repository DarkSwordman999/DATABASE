-- Задача 3.1: топ-3 товара по выручке в каждом магазине (LATERAL, аналог TAXI 114)
-- Запуск: ./help 114
SELECT МАГАЗИН.название AS магазин, т.товар, round(т.выручка, 2) AS выручка
FROM МАГАЗИН
CROSS JOIN LATERAL (
    SELECT ТОВАР.наименование AS товар, sum(ПРОДАЖА.количество * ТОВАР.цена2) AS выручка
      FROM ПРОДАЖА INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
     WHERE ПРОДАЖА.магазин = МАГАЗИН.код
     GROUP BY ТОВАР.наименование
     ORDER BY выручка DESC
     LIMIT 3) т
ORDER BY МАГАЗИН.название, т.выручка DESC;
