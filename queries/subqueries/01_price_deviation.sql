-- Задача 1.1: отклонение суммы продажи от средней суммы продажи
-- (скалярный подзапрос в списке SELECT, аналог TAXI 110)
-- Запуск: ./help 110
SELECT ПРОДАЖА.дата, ТОВАР.наименование AS товар, ПРОДАЖА.количество * ТОВАР.цена2 AS сумма,
       round((SELECT avg(П.количество * Т.цена2)
                FROM ПРОДАЖА П INNER JOIN ТОВАР Т ON Т.код = П.товар), 2) AS средняя,
       round(ПРОДАЖА.количество * ТОВАР.цена2 - (SELECT avg(П.количество * Т.цена2)
                FROM ПРОДАЖА П INNER JOIN ТОВАР Т ON Т.код = П.товар), 2) AS отклонение
FROM ПРОДАЖА
INNER JOIN ТОВАР ON ТОВАР.код = ПРОДАЖА.товар
ORDER BY ПРОДАЖА.дата DESC
LIMIT 10;
