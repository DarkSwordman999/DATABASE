-- Защита ЛР2, вариант 20, задание 1:
-- суммарная выручка от продажи товаров двух поставщиков с заданными именами
-- результат - сводная таблица: поставщик 1 | поставщик 2 | суммарная выручка
-- p1, p2 - названия поставщиков (./help lr2 def 20 1 "ООО Турман" "ЧП Загорье")
-- Текст запроса с подставленными параметрами записывается в переменную psql :q,
-- сценарии выводят его (\echo :q) и выполняют (:q ;  или  EXPLAIN ANALYZE :q ;)
SELECT format($q$SELECT %L AS "поставщик 1", %L AS "поставщик 2",
       sum(ПРОДАЖА.количество * ТОВАР.цена2) AS "суммарная выручка"
FROM ПРОДАЖА
    INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
    INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
WHERE ПОСТАВЩИК.название IN (%L, %L)$q$, :'p1', :'p2', :'p1', :'p2') AS q \gset
