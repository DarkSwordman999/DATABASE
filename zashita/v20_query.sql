-- Защита ЛР2, вариант 20, задание 1:
-- суммарная выручка от продажи товаров двух поставщиков с заданными именами
-- результат - таблица: поставщик 1 | поставщик 2 | суммарная выручка
-- p1, p2 - названия поставщиков (./help zas 20 1 "ООО Турман" "ЧП Загорье")
-- :explain - пусто или EXPLAIN ANALYZE (задаётся сценарием)
:explain
SELECT :'p1' AS "поставщик 1", :'p2' AS "поставщик 2",
       sum(ПРОДАЖА.количество * ТОВАР.цена2) AS "суммарная выручка"
FROM ПРОДАЖА
    INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
    INNER JOIN ПОСТАВЩИК ON ПОСТАВЩИК.код = ТОВАР.поставщик
WHERE ПОСТАВЩИК.название IN (:'p1', :'p2');
