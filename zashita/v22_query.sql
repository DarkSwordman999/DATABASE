-- суммарная выручка от продажи товаров заданной категории
-- результат - сводная таблица: категория | суммарная выручка
-- p1 - наименование категории (./help zas 22 1 мебель)
-- Текст запроса с подставленными параметрами записывается в переменную psql :q,
-- сценарии выводят его (\echo :q) и выполняют (:q ;  или  EXPLAIN ANALYZE :q ;)
SELECT format($q$SELECT %L AS "категория",
       sum(ПРОДАЖА.количество * ТОВАР.цена2) AS "суммарная выручка"
FROM ПРОДАЖА
    INNER JOIN ТОВАР     ON ТОВАР.код = ПРОДАЖА.товар
    INNER JOIN КАТЕГОРИЯ ON КАТЕГОРИЯ.код = ТОВАР.категория
WHERE КАТЕГОРИЯ.наименование = %L$q$, :'p1', :'p1') AS q \gset
