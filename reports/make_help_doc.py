def help_blocks():
    """Тексты блоков справки $Help.<блок> = @' ... '@ из helper/help.ps1."""
    src = read("helper/help.ps1")
    return {m.group(1): m.group(2)
            for m in re.finditer(r"^\$Help\.(\w+) = @'\n(.*?)\n'@", src, re.S | re.M)}


def parse_block(text):
    """Строки блока справки -> части [(подзаголовок, [(команда, назначение, файлы, пример)], [примечания])]."""
    parts = [["", [], []]]
    for line in text.splitlines():
        s = line.strip()
        if not s or s.startswith("=========="):
            continue
        m = re.match(r"^--- (.*) ---$", s)
        if m:
            parts.append([m.group(1), [], []])
            continue
        rows, notes = parts[-1][1], parts[-1][2]
        # пример (несколько - через 3 и более пробела) и его строки-продолжения
        if rows and (s.startswith("пример:") or re.match(r"^\s{40,}\./help ", line)):
            ex = re.sub(r"\s{3,}", "\n", s.removeprefix("пример:").strip())
            rows[-1][3] = (rows[-1][3] + "\n" + ex).strip()
            continue
        m = re.match(r"^(\./help .+?)\s+- (.*)$", s)
        if m:
            desc, files = m.group(2), ""
            f = re.search(r"\s+\[([^\]]+)\]$", desc)
            if f:
                desc, files = desc[:f.start()], f.group(1)
            rows.append([m.group(1), desc, files, ""])
        else:
            notes.append(s.strip("()"))
    return [p for p in parts if p[1] or p[2]]


def menu_sections():
    """helper/menu.txt -> [(раздел, [(команда, описание, файл, пример)])]."""
    sections = []
    for line in read("helper/menu.txt").splitlines():
        if not line or line.startswith("#"):
            continue
        if line.startswith("== "):
            sections.append((line[3:].capitalize(), []))
            continue
        f = line.split("|") + [""] * 7
        cmd = f"./help {f[0]}" + (f" {f[2]}" if f[2] else "")
        sections[-1][1].append((cmd, f[4], f[1], f"./help {f[0]} {f[5]}" if f[5] else ""))
    return sections


