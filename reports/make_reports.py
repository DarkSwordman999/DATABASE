def _avg_current(name):
    m = re.search(r"среднее\s*\|\s*([\d.]+)", out(name))
    return float(m.group(1))


def _timing_ms(name):
    vals = re.findall(r"Время: ([\d ]+,\d+) мс", out(name))
    return [float(x.replace(" ", "").replace(",", ".")) for x in vals]


