def _split_sql(path, start, end=None):
    text = read(path)
    a = text.index(start)
    b = text.index(end, a) if end else len(text)
    lines = text[a:b].rstrip().splitlines()
    while lines and lines[-1].startswith("-- ---"):
        lines.pop()
    return "\n".join(lines).rstrip()


